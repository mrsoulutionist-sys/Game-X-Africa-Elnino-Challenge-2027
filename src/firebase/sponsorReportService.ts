function escapeCsvCell(raw: string | number | boolean | null | undefined): string {
  const s = raw === null || raw === undefined ? '' : String(raw);
  if (/[",\r\n]/.test(s)) {
    return `"${s.replace(/"/g, '""')}"`;
  }
  return s;
}

function toCsvDocument(headers: string[], rows: Array<Array<string | number | boolean | null | undefined>>): string {
  const lines: string[] = [headers.map(escapeCsvCell).join(',')];
  for (const row of rows) {
    lines.push(row.map(escapeCsvCell).join(','));
  }
  // UTF-8 BOM ensures Excel opens South African R/UTF-8 symbols cleanly
  return `\uFEFF${lines.join('\r\n')}\r\n`;
}

export function buildSponsorCsvContent(params: {
  kind: SponsorCsvReportKind;
  snapshot: LeaderboardSnapshot;
  batches: HarvestBatch[];
  saleEvents: GradeSaleEventRecord[];
  storeListings: StoreListing[];
  competitionRuns?: CompetitionRunRecord[];
  sponsorSlots: Record<string, SponsorSlotAssignment>;
}): { filename: string; csv: string; rowCount: number } {
  const {
    kind,
    snapshot,
    batches,
    storeListings,
    competitionRuns = [],
    sponsorSlots,
  } = params;

  const dateStamp = new Date().toISOString().slice(0, 10);

  if (kind === 'school_grade_impact') {
    const headers = [
      'School_Canonical',
      'Matched_School_Spellings',
      'Grade_Or_Summary',
      'Active_Students',
      'Produce_Grown_And_Sold',
      'Harvest_Units',
      'Estimated_Mass_KG',
      'Mass_Label',
      'Food_Servings_Est',
      'Store_Units_Sold',
      'Store_Sales_ZAR',
    ];
    const rows: Array<Array<string | number>> = [];

    for (const school of snapshot.groupedSchools) {
      for (const gradeRow of school.grades) {
        const produceText =
          gradeRow.producedItems.length > 0
            ? gradeRow.producedItems.map((p) => `${p.title} (${p.units})`).join('; ')
            : gradeRow.topItems.length > 0
              ? gradeRow.topItems.join('; ')
              : 'In Progress';
        rows.push([
          school.canonicalSchoolName,
          school.matchedVariants.join(' | '),
          gradeRow.grade,
          gradeRow.studentCount,
          produceText,
          gradeRow.harvestUnits,
          gradeRow.harvestKg,
          gradeRow.harvestMassLabel,
          gradeRow.harvestUnits * 2,
          gradeRow.unitsSold,
          gradeRow.salesZar.toFixed(2),
        ]);
      }
      // Combined School Total Rollup Row
      rows.push([
        school.canonicalSchoolName,
        school.matchedVariants.join(' | '),
        `COMBINED SCHOOL TOTAL (${school.grades.length} Grades)`,
        school.studentCount,
        `${school.grades.length} Active Grade(s)`,
        school.totalHarvestUnits,
        school.totalKg,
        school.massLabel,
        school.totalFoodServings,
        school.totalUnitsSold,
        school.totalSalesZar.toFixed(2),
      ]);
    }

    if (rows.length === 0) {
      rows.push([
        'No School Harvest Activity Yet',
        '',
        'All Grades',
        0,
        'Waiting for first harvest',
        0,
        0,
        '0 kg',
        0,
        0,
        '0.00',
      ]);
    }

    return {
      filename: `gamex-school-grade-impact-${dateStamp}.csv`,
      csv: toCsvDocument(headers, rows),
      rowCount: rows.length,
    };
  }

  if (kind === 'harvest_batches_ledger') {
    const headers = [
      'Batch_ID',
      'Harvested_At_ISO',
      'School_Canonical',
      'School_Typed_Name',
      'Grade',
      'Learner_Alias_POPIA',
      'Crop_Or_Compost_Item',
      'Category',
      'Quantity_Units',
      'Estimated_Mass_KG',
      'Live_Store_Shelf_Remaining',
    ];

    const listingByKey = new Map<string, number>();
    for (const l of storeListings) {
      listingByKey.set(`${l.schoolId}|${l.grade}|${l.title.toLowerCase()}`, l.quantityAvailable);
    }

    const rows: Array<Array<string | number>> = batches.map((b) => {
      const cluster = snapshot.resolveSchoolCluster(b.schoolName || b.schoolId);
      const mass = formatHarvestMass(b.quantity);
      const shelfKey = `${b.schoolId}|${b.grade}|${b.itemTitle.toLowerCase()}`;
      const remaining = listingByKey.get(shelfKey) ?? 0;
      return [
        b.batchId,
        new Date(b.harvestedAtMs).toISOString(),
        cluster.canonicalName,
        b.schoolName || cluster.canonicalName,
        b.grade,
        b.studentName,
        b.itemTitle,
        b.category === 'mulch_compost' ? 'Door 3 Compost & Mulch' : 'Door 2 Hydroponic Produce',
        b.quantity,
        mass.kg,
        remaining,
      ];
    });

    return {
      filename: `gamex-harvest-ledger-${dateStamp}.csv`,
      csv: toCsvDocument(headers, rows),
      rowCount: rows.length,
    };
  }

  // sponsor_roi_inventory
  const totalStudents = snapshot.rankedStudents.length;
  const totalSchools = snapshot.groupedSchools.length;
  const totalLitresSaved = snapshot.rankedStudents.reduce((s, r) => s + r.litresSaved, 0);
  const totalServings = snapshot.rankedStudents.reduce((s, r) => s + r.foodServings, 0);

  const headers = [
    'Slot_ID',
    'Room',
    'Placement_Target',
    'Category',
    'Sponsor_Status',
    'Display_Mode',
    'Partner_Name',
    'Tagline',
    'Has_Uploaded_Logo',
    'Active_Schools_Reach',
    'Active_Learners_Reach',
    'Platform_Total_Harvest_Mass',
    'Platform_Water_Saved_Litres',
    'Platform_Food_Servings',
    'Platform_Produce_Sales_ZAR',
    'Competition_Speedruns_Logged',
  ];

  const rows: Array<Array<string | number>> = SPONSOR_SLOT_CATALOG.map((item) => {
    const assigned = sponsorSlots[item.slotId];
    const isActive = Boolean(assigned?.active);
    return [
      item.slotId,
      item.room.toUpperCase(),
      item.label,
      item.categoryLabel,
      isActive ? 'SPONSORED (LIVE IN 3D/UI)' : 'AVAILABLE',
      isActive ? assigned!.displayMode.toUpperCase() : 'DEFAULT_PLACEHOLDER',
      isActive && assigned?.partnerName ? assigned.partnerName : item.defaultPartnerName,
      isActive && assigned?.tagline ? assigned.tagline : item.defaultTagline,
      isActive && Boolean(assigned?.logoDataUrl) ? 'YES' : 'NO',
      totalSchools,
      totalStudents,
      snapshot.totalMassAllLabel,
      Math.round(totalLitresSaved),
      totalServings,
      snapshot.totalProduceSalesZar.toFixed(2),
      competitionRuns.length,
    ];
  });

  return {
    filename: `gamex-sponsor-roi-inventory-${dateStamp}.csv`,
    csv: toCsvDocument(headers, rows),
    rowCount: rows.length,
  };
}

export function triggerCsvDownload(filename: string, csvContent: string): void {
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}
